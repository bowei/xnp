// The DOT encoding is the interchange format of the tool: `generate graph` and
// `fetch` write it, `generate k8s -graph` reads it back, and graphviz renders
// it untouched.
//
// The vertex metadata -- what kind a vertex is, which namespace and node a pod
// is placed in, a policy's direction and type -- rides in DOT attributes rather
// than in comments. The doc describes it as comment metadata, but a comment is
// exactly what every DOT tool in the chain is entitled to discard: `dot -Tsvg`
// then `dot -Txdot` round trip loses it, and a graph a user has laid out by
// hand comes back unreadable. Attributes survive that, and graphviz ignores the
// ones it does not know.
//
// The placement and policy edges are redundant with the attributes for pods but
// not for policies, and they are what makes the file a graph rather than a
// serialized struct -- rendering it has to show the relationships.

const dotName = "npgraph"

// WriteDOT encodes g. The output is deterministic for a given graph: vertices
// and edges come out in the order the graph holds them, which is the order the
// generator built them in and the sorted order fetch imposes.
func WriteDOT(w io.Writer, g *Graph) error {
	bw := newErrWriter(w)

	bw.printf("digraph %s {\n", dotName)
	bw.printf("  // Generated by npgraph. Vertex metadata is carried in DOT attributes.\n")

	bw.printf("\n  // Nodes\n")
	for _, n := range g.Nodes {
		bw.printf("  %s [kind=%q];\n", quoteID(n.Name), KindNode)
	}

	bw.printf("\n  // Namespaces\n")
	for _, ns := range g.Namespaces {
		bw.printf("  %s [kind=%q];\n", quoteID(ns.Name), KindNamespace)
	}

	bw.printf("\n  // Pods\n")
	for _, p := range g.Pods {
		bw.printf("  %s [kind=%q, namespace=%q, node=%q];\n", quoteID(p.Name), KindPod, p.Namespace, p.Node)
	}

	bw.printf("\n  // Network policies\n")
	for _, p := range g.Policies {
		bw.printf("  %s [kind=%q, namespace=%q, direction=%q, type=%q];\n",
			quoteID(p.Name), KindPolicy, p.Namespace, p.Direction, p.Type)
	}

	bw.printf("\n  // Placement: node -> pod, namespace -> pod\n")
	for _, p := range g.Pods {
		bw.printf("  %s -> %s;\n", quoteID(p.Node), quoteID(p.Name))
		bw.printf("  %s -> %s;\n", quoteID(p.Namespace), quoteID(p.Name))
	}

	for _, p := range g.Policies {
		bw.printf("\n  // %s: %s, %s\n", p.Name, p.Direction, p.Type)
		for _, in := range p.In {
			bw.printf("  %s -> %s; // In\n", quoteID(in), quoteID(p.Name))
		}
		for _, out := range p.Out {
			bw.printf("  %s -> %s; // Out\n", quoteID(p.Name), quoteID(out))
		}
		for _, ns := range p.OutNamespaces {
			bw.printf("  %s -> %s; // Out, whole namespace\n", quoteID(p.Name), quoteID(ns))
		}
	}

	bw.printf("}\n")

	return bw.flush()
}

// quoteID renders a vertex name as a DOT id. Everything is quoted rather than
// only the names that need it: the generated names are safe bare, but a fetched
// one carries a '/' and a '#', and one rule is easier to trust than two.
func quoteID(s string) string {
	return `"` + strings.NewReplacer(`\`, `\\`, `"`, `\"`).Replace(s) + `"`
}

// ParseDOT reads a graph written by WriteDOT.
//
// It is a parser for the subset of DOT this tool emits, not for the language:
// vertex and edge statements with an optional attribute list, comments, and
// nothing else. Subgraphs, default attribute statements and edge chains are
// rejected rather than half-understood, because a graph that came back missing
// its relationships would generate a cluster with silently fewer policies.
func ParseDOT(r io.Reader) (*Graph, error) {
	src, err := io.ReadAll(r)
	if err != nil {
		return nil, err
	}

	stmts, err := dotStatements(string(src))
	if err != nil {
		return nil, err
	}

	g := &Graph{}
	// Edges are collected and resolved after every vertex is known: an edge's
	// meaning is decided by the kinds of its endpoints, and a file is not
	// obliged to declare both before using them.
	type edge struct{ from, to string }
	var edges []edge
	kinds := map[string]Kind{}
	idx := &index{
		nodes:      map[string]*Node{},
		namespaces: map[string]*Namespace{},
		pods:       map[string]*Pod{},
		policies:   map[string]*Policy{},
	}

	for _, stmt := range stmts {
		ids, attrs, err := parseDOTStatement(stmt)
		if err != nil {
			return nil, err
		}
		switch len(ids) {
		case 1:
			name := ids[0]
			if _, dup := kinds[name]; dup {
				return nil, fmt.Errorf("duplicate declaration of vertex %q", name)
			}
			kind := Kind(attrs["kind"])
			switch kind {
			case KindNode:
				n := &Node{Name: name}
				g.Nodes = append(g.Nodes, n)
				idx.nodes[name] = n
			case KindNamespace:
				ns := &Namespace{Name: name}
				g.Namespaces = append(g.Namespaces, ns)
				idx.namespaces[name] = ns
			case KindPod:
				p := &Pod{Name: name, Namespace: attrs["namespace"], Node: attrs["node"]}
				g.Pods = append(g.Pods, p)
				idx.pods[name] = p
			case KindPolicy:
				p := &Policy{
					Name:      name,
					Namespace: attrs["namespace"],
					Direction: Direction(attrs["direction"]),
					Type:      PolicyType(attrs["type"]),
				}
				g.Policies = append(g.Policies, p)
				idx.policies[name] = p
			case "":
				return nil, fmt.Errorf("vertex %q has no kind attribute", name)
			default:
				return nil, fmt.Errorf("vertex %q has unknown kind %q", name, kind)
			}
			kinds[name] = kind
		case 2:
			edges = append(edges, edge{from: ids[0], to: ids[1]})
		default:
			return nil, fmt.Errorf("unsupported statement %q: edge chains are not supported", stmt)
		}
	}

	for _, e := range edges {
		fromKind, ok := kinds[e.from]
		if !ok {
			return nil, fmt.Errorf("edge %q -> %q: %q is not declared", e.from, e.to, e.from)
		}
		toKind, ok := kinds[e.to]
		if !ok {
			return nil, fmt.Errorf("edge %q -> %q: %q is not declared", e.from, e.to, e.to)
		}

		switch {
		case fromKind == KindNode && toKind == KindPod:
			// Redundant with the pod's own attribute, and so a consistency
			// check rather than an assignment -- except when the attribute is
			// absent, which is how a hand-written graph places its pods.
			pod := idx.pods[e.to]
			if pod.Node != "" && pod.Node != e.from {
				return nil, fmt.Errorf("pod %q is on node %q by attribute but node %q by edge", pod.Name, pod.Node, e.from)
			}
			pod.Node = e.from
		case fromKind == KindNamespace && toKind == KindPod:
			pod := idx.pods[e.to]
			if pod.Namespace != "" && pod.Namespace != e.from {
				return nil, fmt.Errorf("pod %q is in namespace %q by attribute but namespace %q by edge", pod.Name, pod.Namespace, e.from)
			}
			pod.Namespace = e.from
		case fromKind == KindPod && toKind == KindPolicy:
			p := idx.policies[e.to]
			p.In = append(p.In, e.from)
			// A policy's namespace follows from its In set, which is why a
			// hand-written graph need not spell it out.
			if p.Namespace == "" {
				p.Namespace = idx.pods[e.from].Namespace
			}
		case fromKind == KindPolicy && toKind == KindPod:
			p := idx.policies[e.from]
			p.Out = append(p.Out, e.to)
		case fromKind == KindPolicy && toKind == KindNamespace:
			p := idx.policies[e.from]
			p.OutNamespaces = append(p.OutNamespaces, e.to)
		default:
			return nil, fmt.Errorf("edge %q -> %q: %s -> %s is not a relationship in the resource graph", e.from, e.to, fromKind, toKind)
		}
	}

	// A policy vertex that never says which direction it is cannot be rendered,
	// but the common case of a hand-written graph is one that omits everything
	// optional, so the defaults are the ones that lose the least meaning.
	for _, p := range g.Policies {
		if p.Direction == "" {
			p.Direction = DirectionIngress
		}
		if p.Type == "" {
			p.Type = classifyPolicy(g, p)
		}
	}

	if err := g.Validate(); err != nil {
		return nil, err
	}
	return g, nil
}

// classifyPolicy infers a policy's type from the reach of its Out set, for
// graphs that did not record one -- a hand-written graph, or a fetched cluster,
// where the type is a description of a policy that already exists rather than
// an instruction for building one.
//
// It cannot distinguish Global from a CrossNSBroad that happens to span every
// namespace, and calls that Global: reaching the whole cluster is what Global
// means to everything downstream.
func classifyPolicy(g *Graph, p *Policy) PolicyType {
	spanned := g.OutNamespaces(p)
	// SameNS is a claim about which namespace, not just how many: a policy
	// whose only peers are in one other namespace is as cross-namespace as one
	// spanning five, and calling it SameNS would tell a renderer to expect no
	// cross-namespace resolution at all.
	if len(spanned) == 0 || (len(spanned) == 1 && spanned[p.Namespace]) {
		return PolicySameNS
	}
	switch {
	case len(spanned) >= len(g.Namespaces) && len(g.Namespaces) > 1:
		return PolicyGlobal
	case len(spanned) > FocusedNamespaceLimit:
		return PolicyCrossNSBroad
	default:
		return PolicyCrossNSFocused
	}
}

// dotStatements strips comments and the enclosing `digraph <id> { ... }`, and
// splits what is left into statements. Statements end at a ';' or at a newline,
// which is DOT's own rule and what lets the emitted file read naturally.
func dotStatements(src string) ([]string, error) {
	var (
		stmts   []string
		cur     strings.Builder
		inQuote bool
		escaped bool
		depth   int
		header  bool
	)

	flush := func() {
		s := strings.TrimSpace(cur.String())
		cur.Reset()
		if s != "" {
			stmts = append(stmts, s)
		}
	}

	for i := 0; i < len(src); i++ {
		c := src[i]

		if inQuote {
			cur.WriteByte(c)
			switch {
			case escaped:
				escaped = false
			case c == '\\':
				escaped = true
			case c == '"':
				inQuote = false
			}
			continue
		}

		switch {
		case c == '"':
			inQuote = true
			cur.WriteByte(c)
		case c == '/' && i+1 < len(src) && src[i+1] == '/':
			// Line comment: everything to the end of the line, which also ends
			// the statement it trails.
			for i < len(src) && src[i] != '\n' {
				i++
			}
			flush()
		case c == '/' && i+1 < len(src) && src[i+1] == '*':
			end := strings.Index(src[i+2:], "*/")
			if end < 0 {
				return nil, fmt.Errorf("unterminated block comment")
			}
			i += 2 + end + 1
		case c == '{':
			depth++
			if depth > 1 {
				return nil, fmt.Errorf("subgraphs are not supported")
			}
			// The graph header is not a statement; it is whatever preceded the
			// brace.
			cur.Reset()
			header = true
		case c == '}':
			depth--
			if depth < 0 {
				return nil, fmt.Errorf("unbalanced '}'")
			}
			flush()
		case c == ';' || c == '\n':
			flush()
		default:
			cur.WriteByte(c)
		}
	}

	if inQuote {
		return nil, fmt.Errorf("unterminated quoted string")
	}
	if depth != 0 {
		return nil, fmt.Errorf("unbalanced '{'")
	}
	if !header {
		return nil, fmt.Errorf("not a DOT graph: no '{' found")
	}
	flush()

	return stmts, nil
}

// parseDOTStatement splits one statement into its ids and its attribute list.
// One id is a vertex declaration, two are an edge.
func parseDOTStatement(stmt string) (ids []string, attrs map[string]string, err error) {
	body := stmt
	attrs = map[string]string{}

	if open := indexOutsideQuotes(stmt, '['); open >= 0 {
		if !strings.HasSuffix(strings.TrimSpace(stmt), "]") {
			return nil, nil, fmt.Errorf("statement %q: unterminated attribute list", stmt)
		}
		body = stmt[:open]
		attrList := strings.TrimSpace(stmt[open+1:])
		attrList = strings.TrimSuffix(attrList, "]")
		attrs, err = parseDOTAttrs(attrList)
		if err != nil {
			return nil, nil, fmt.Errorf("statement %q: %w", stmt, err)
		}
	}

	for _, part := range strings.Split(body, "->") {
		id, err := unquoteID(strings.TrimSpace(part))
		if err != nil {
			return nil, nil, fmt.Errorf("statement %q: %w", stmt, err)
		}
		if id == "" {
			return nil, nil, fmt.Errorf("statement %q: empty vertex id", stmt)
		}
		ids = append(ids, id)
	}

	// An undirected edge in a digraph is a syntax error in DOT, and letting it
	// through here would silently drop half the graph.
	if strings.Contains(body, "--") {
		return nil, nil, fmt.Errorf("statement %q: undirected edges are not supported", stmt)
	}

	return ids, attrs, nil
}

func parseDOTAttrs(s string) (map[string]string, error) {
	attrs := map[string]string{}
	for _, field := range splitOutsideQuotes(s, ',') {
		field = strings.TrimSpace(field)
		if field == "" {
			continue
		}
		eq := indexOutsideQuotes(field, '=')
		if eq < 0 {
			return nil, fmt.Errorf("attribute %q is not a key=value pair", field)
		}
		key, err := unquoteID(strings.TrimSpace(field[:eq]))
		if err != nil {
			return nil, err
		}
		val, err := unquoteID(strings.TrimSpace(field[eq+1:]))
		if err != nil {
			return nil, err
		}
		attrs[key] = val
	}
	return attrs, nil
}

func unquoteID(s string) (string, error) {
	if !strings.HasPrefix(s, `"`) {
		return s, nil
	}
	if len(s) < 2 || !strings.HasSuffix(s, `"`) {
		return "", fmt.Errorf("unterminated quoted id %q", s)
	}
	var out strings.Builder
	body := s[1 : len(s)-1]
	for i := 0; i < len(body); i++ {
		if body[i] == '\\' && i+1 < len(body) {
			i++
			out.WriteByte(body[i])
			continue
		}
		out.WriteByte(body[i])
	}
	return out.String(), nil
}

func indexOutsideQuotes(s string, target byte) int {
	inQuote := false
	for i := 0; i < len(s); i++ {
		switch {
		case s[i] == '\\' && inQuote:
			i++
		case s[i] == '"':
			inQuote = !inQuote
		case s[i] == target && !inQuote:
			return i
		}
	}
	return -1
}

func splitOutsideQuotes(s string, sep byte) []string {
	var (
		out     []string
		cur     strings.Builder
		inQuote bool
	)
	for i := 0; i < len(s); i++ {
		switch {
		case s[i] == '\\' && inQuote:
			cur.WriteByte(s[i])
			if i+1 < len(s) {
				i++
				cur.WriteByte(s[i])
			}
		case s[i] == '"':
			inQuote = !inQuote
			cur.WriteByte(s[i])
		case s[i] == sep && !inQuote:
			out = append(out, cur.String())
			cur.Reset()
		default:
			cur.WriteByte(s[i])
		}
	}
	out = append(out, cur.String())
	return out
}

// sortGraph puts a graph into a canonical order, so that two runs that found
// the same cluster produce byte-identical DOT. The generator's own order is
// already deterministic; this is for fetch, which reads maps and API list
// responses.
func sortGraph(g *Graph) {
	sort.Slice(g.Nodes, func(i, j int) bool { return g.Nodes[i].Name < g.Nodes[j].Name })
	sort.Slice(g.Namespaces, func(i, j int) bool { return g.Namespaces[i].Name < g.Namespaces[j].Name })
	sort.Slice(g.Pods, func(i, j int) bool { return g.Pods[i].Name < g.Pods[j].Name })
	sort.Slice(g.Policies, func(i, j int) bool { return g.Policies[i].Name < g.Policies[j].Name })
	for _, p := range g.Policies {
		sort.Strings(p.In)
		sort.Strings(p.Out)
		sort.Strings(p.OutNamespaces)
	}
}
